import 'package:flutter/material.dart';

/// O SÍMBOLO da marca: a vagem de soja e a espiga de trigo, lado a lado.
///
/// Os traçados vêm do SVG oficial (`agrobarter-horizontal-negativa.svg`) e são
/// desenhados aqui direto, sem pacote de SVG: eles só usam `M`, `L` e `Z`
/// absolutos, e ler isso é meia dúzia de linhas. O mesmo texto alimenta o
/// comprovante em PDF (ver [brandMarkSvg]) — um desenho só nas duas saídas.
class BrandMark extends StatelessWidget {
  /// Altura do símbolo. A largura segue a proporção do desenho.
  final double height;

  /// Cor da vagem: branca sobre a cor institucional, verde sobre fundo claro.
  final Color podColor;

  /// Cor da espiga: o dourado da marca nos dois fundos.
  final Color wheatColor;

  const BrandMark({
    super.key,
    required this.height,
    required this.podColor,
    required this.wheatColor,
  });

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      width: height * brandMarkAspect,
      height: height,
      child: CustomPaint(
        painter: _BrandMarkPainter(podColor, wheatColor),
      ),
    );
  }
}

/// Recorte do desenho dentro das coordenadas originais do SVG.
const Rect _viewBox = Rect.fromLTWH(23, 11.5, 56.7, 75.5);

/// Largura ÷ altura do símbolo.
final double brandMarkAspect = _viewBox.width / _viewBox.height;

/// O símbolo como SVG, para quem não desenha com `Canvas` (o PDF).
String brandMarkSvg({required String podHex, required String wheatHex}) =>
    '<svg xmlns="http://www.w3.org/2000/svg" '
    'viewBox="${_viewBox.left} ${_viewBox.top} ${_viewBox.width} ${_viewBox.height}">'
    '<path d="$_podPath" fill="$podHex" fill-rule="evenodd"/>'
    '<path d="$_wheatPath" fill="$wheatHex" fill-rule="evenodd"/>'
    '</svg>';

class _BrandMarkPainter extends CustomPainter {
  final Color pod;
  final Color wheat;
  _BrandMarkPainter(this.pod, this.wheat);

  static final Path _pod = _parse(_podPath);
  static final Path _wheat = _parse(_wheatPath);

  @override
  void paint(Canvas canvas, Size size) {
    final scale = size.height / _viewBox.height;
    canvas.save();
    canvas.scale(scale);
    canvas.translate(-_viewBox.left, -_viewBox.top);
    canvas.drawPath(_pod, Paint()..color = pod);
    canvas.drawPath(_wheat, Paint()..color = wheat);
    canvas.restore();
  }

  @override
  bool shouldRepaint(_BrandMarkPainter old) =>
      old.pod != pod || old.wheat != wheat;
}

/// Lê um traçado feito só de `M`, `L` e `Z` absolutos.
Path _parse(String d) {
  final path = Path()..fillType = PathFillType.evenOdd;
  final tokens = RegExp(r'[MLZ]|-?\d*\.?\d+').allMatches(d).map((m) => m[0]!);
  var cmd = 'M';
  double? x;
  for (final t in tokens) {
    if (t == 'M' || t == 'L') {
      cmd = t;
    } else if (t == 'Z') {
      path.close();
    } else if (x == null) {
      x = double.parse(t);
    } else {
      final y = double.parse(t);
      if (cmd == 'M') {
        path.moveTo(x, y);
        cmd = 'L'; // pares seguidos a um M são linhas, como no SVG
      } else {
        path.lineTo(x, y);
      }
      x = null;
    }
  }
  return path;
}

